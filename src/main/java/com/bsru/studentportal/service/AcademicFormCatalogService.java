  /**
   * ค้นหาเอกสาร/แบบฟอร์มที่ตรงกับคำถามของผู้ใช้
   */
  public List<AcademicFormInfo> findMatchingForms(String query) {
    if (query == null || query.isBlank()) {
      return List.of();
    }
    String q = query.toLowerCase(Locale.ROOT).trim();
    Set<AcademicFormInfo> matched = new LinkedHashSet<>();

    for (AcademicFormInfo form : CATALOG) {
      if (form.codePattern().matcher(query).find()) {
        matched.add(form);
        continue;
      }
      for (String kw : form.keywords()) {
        if (q.contains(kw.toLowerCase(Locale.ROOT))) {
          matched.add(form);
          break;
        }
      }
    }

    // กรณีถามเกี่ยวกับ ทบ.5 ที่ต้องใช้ ทบ.17 คู่กัน หรือถามรวมแบบฟอร์มทั้งหมด
    if (matched.isEmpty() && isGeneralCatalogRequest(q)) {
      return CATALOG;
    }

    return new ArrayList<>(matched);
  }

  /**
   * สร้างบริบทข้อมูลแบบฟอร์มทั้งหมดและแบบฟอร์มที่ตรงกับคำถาม เพื่อส่งให้ Gemini
   * ตอบพร้อมคำอธิบายที่ถูกต้อง
   */
  public String buildPromptContext(String query, List<AcademicFormInfo> matchedForms) {
    StringBuilder sb = new StringBuilder();
    sb.append("\n[คลังเอกสารคำร้องและแบบฟอร์มทางการ มบส. (สำนักส่งเสริมวิชาการและงานทะเบียน / กิจการนักศึกษา)]:\n");
    if (!matchedForms.isEmpty()) {
      sb.append(
          "ระบบได้แนบไฟล์ PDF ของเอกสารต่อไปนี้ไว้ในการ์ดดาวน์โหลดใต้ข้อความของคุณแล้ว — กรุณาตอบให้กระชับ ตรงประเด็น ตอบเฉพาะเท่าที่ผู้ใช้ถาม หากผู้ใช้เพียงขอเอกสาร ให้แจ้งสั้นๆ 1-3 บรรทัดพร้อมแจ้งให้เปิดดูหรือดาวน์โหลดจากการ์ดด้านล่าง ห้ามใส่ขั้นตอนหรือเงื่อนไขยาวเหยียดเว้นแต่ผู้ใช้จะถามถึงขั้นตอน และห้ามสร้างลิงก์จำลองในข้อความ:\n\n");
      for (AcademicFormInfo f : matchedForms) {
        sb.append(f.detailedExplanation()).append("\n\n");
      }
    } else {
      sb.append(
          "รายการแบบฟอร์มทางการที่มีในระบบ (หากนักศึกษาต้องการขอไฟล์ใด สามารถพิมพ์ชื่อเอกสารหรือรหัส ทบ. เพื่อให้ระบบส่งไฟล์ PDF ให้ดาวน์โหลดได้ทันที):\n");
      for (AcademicFormInfo f : CATALOG) {
        sb.append("- ").append(f.code()).append(": ").append(f.title())
            .append(" — ").append(f.summary()).append("\n");
      }
    }
    return sb.toString();
  }

  /**
   * สร้างคำตอบอธิบายละเอียดทันทีในโหมด Fallback เมื่อนักศึกษาถามหรือขอเอกสาร
   */
  public String buildFallbackReply(String query, List<AcademicFormInfo> matchedForms) {
    if (matchedForms == null || matchedForms.isEmpty()) {
      return null;
    }
    if (matchedForms.size() == CATALOG.size()) {
      StringBuilder sb = new StringBuilder(
          "📄 **รายการแบบฟอร์มคำร้องและเอกสารทางการของนักศึกษา BSRU ทั้งหมด 16 รายการ**\n");
      sb.append("คุณสามารถกด **เปิดดู PDF** หรือ **ดาวน์โหลด** เอกสารที่ต้องการจากการ์ดไฟล์ด้านล่างได้เลยครับ:\n\n");
      for (AcademicFormInfo f : CATALOG) {
        sb.append("- **").append(f.code()).append("** — ").append(f.title()).append(": ").append(f.summary())
            .append("\n");
      }
      return sb.toString().trim();
    }

    StringBuilder sb = new StringBuilder();
    sb.append(
        "จัดเตรียมไฟล์เอกสารที่คุณต้องการให้เรียบร้อยแล้วครับ 📄 สามารถกด **เปิดดู PDF** หรือ **ดาวน์โหลดเอกสาร** จากการ์ดด้านล่างได้เลย โดยมีรายละเอียดและขั้นตอนดังนี้ครับ:\n\n");
    for (int i = 0; i < matchedForms.size(); i++) {
      if (i > 0)
        sb.append("\n\n---\n\n");
      sb.append(matchedForms.get(i).detailedExplanation());
    }
    return sb.toString().trim();
  }
